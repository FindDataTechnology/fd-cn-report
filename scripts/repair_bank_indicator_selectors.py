#:   601398 杠杆率 7.51 → 取成 7.75（上年）；601288 四项迁徙率 1.28/21.30/37.25/65.62
#:   → 取成 1.39/23.85/35.45/17.29（第三列）。有值、无告警、静默错列。
#: 所以每条 note 都必须显式钉住「第一个数值列＝本报告期」。
PERIOD_HINT = (
    "口径：取**本报告期**的数值，即表中**第一个数值列**（表头为报告期末日期，"
    "如 2025 年 12 月 31 日）。⚠️表里常并列多个年度/季度列，**不要**取上年或前年列。"
)


def _selectors(chain: list[str], company: dict[str, list[str]] | None = None) -> list[dict]:
    """公司级选择器前置 + 全局链；最后一个选择器标 fallback，与既有规则形状一致。"""
    out: list[dict] = []
    for code, titles in (company or {}).items():
        for title in titles:
            out.append({"section": title, "company": [code]})
    for i, section in enumerate(chain):
        sel = {"section": section}
        if i == len(chain) - 1 and i > 0:
            sel["fallback"] = True
        out.append(sel)
    return out


def _decode_json(raw, want: type):
    """解码可能被套了多层 JSON 的列值，直到得到 ``want`` 类型或放弃。

    daas.db 里这些列历史上有单层、双层、甚至 `selectors` 自身被存成 JSON 字符串的
    混杂形态（实测 id 1831 的 selectors 就是字符串 `'[{"section": "财务指标"}]'`）。
    逐层解到目标类型为止，避免一遇到非预期形态就把整段 source 丢掉。
    """
    if raw is None:
        return None
    cur = raw
    for _ in range(3):
        if isinstance(cur, want):
            return cur
        if not isinstance(cur, str):
            break
        try:
            cur = json.loads(cur)
        except (TypeError, ValueError):
            return None
    return cur if isinstance(cur, want) else None


def _sections_of(old) -> list:
    """把 selectors 值规范化成段名列表，仅用于打印差异。"""
    sels = _decode_json(old, list)
    if not sels:
        return []
    return [s.get("section") if isinstance(s, dict) else str(s) for s in sels]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", default=str(DEFAULT_DB))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    db = Path(args.db)
    if not db.exists():
        raise SystemExit(f"DB 不存在：{db}")

    conn = sqlite3.connect(str(db), timeout=30)
    conn.row_factory = sqlite3.Row
    changed = same = 0
    try:
        for indicator, chain in SELECTOR_CHAINS.items():
            selectors = _selectors(chain, COMPANY_SELECTORS.get(indicator))
            position_json = json.dumps(selectors, ensure_ascii=False)
            rows = conn.execute(
                "SELECT id, source, position, note FROM llm_rules WHERE indicator = ? ORDER BY id",
                (indicator,),
            ).fetchall()
            if not rows:
                print(f"[warn] {indicator}: 无规则行，跳过")
                continue
            for row in rows:
                src = _decode_json(row["source"], dict) or {}
                old = _decode_json(src.get("selectors"), list)
                note = NOTES.get(indicator)
                want_note = ((note + " ") if note else "") + PERIOD_HINT
                if (old == selectors and (row["position"] or "") == position_json
                        and (row["note"] or "") == want_note):
                    same += 1
                    continue
                src["selectors"] = selectors
                src.setdefault("extractor", "llm")
                # 每条银行指标 note 都带上「本报告期」口径（原有的行名闸门说明保留在前）
                note = ((note + " ") if note else "") + PERIOD_HINT
                print(f"[fix] id={row['id']} {indicator}: "
                      f"{_sections_of(old)} -> {chain} [note]")
                if not args.dry_run:
                    conn.execute(
                        "UPDATE llm_rules SET source = ?, position = ?, note = ? WHERE id = ?",
                        (json.dumps(src, ensure_ascii=False), position_json, note, row["id"]),
                    )
                changed += 1
        if not args.dry_run:
            conn.commit()
    finally:
        conn.close()

    print(f"\nchanged={changed} already_ok={same} dry_run={args.dry_run} "
          f"untouched={list(UNTOUCHED)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
